// 1.5. IndexScan Physical Operator
// ==========================================
pub struct PhysicalIndexScan {
    schema: Schema,
    table_name: String,
    index_name: String,
    range: Option<(PlanKey, PlanKey)>,
    columns: Option<Vec<String>>,
}

impl PhysicalIndexScan {
    pub fn new(
        schema: Schema,
        table_name: String,
        index_name: String,
        range: Option<(PlanKey, PlanKey)>,
        columns: Option<Vec<String>>,
    ) -> Self {
        Self {
            schema,
            table_name,
            index_name,
            range,
            columns,
        }
    }
}

impl PhysicalOperator for PhysicalIndexScan {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let (start, end) = match &self.range {
            Some((start_key, end_key)) => (start_key.resolve(params)?, end_key.resolve(params)?),
            None => {
                let idx_def = self
                    .schema
                    .indexes
                    .iter()
                    .find(|idx| idx.name == self.index_name)
                    .ok_or_else(|| {
                        format!(
                            "Index '{}' not found in schema during execution",
                            self.index_name
                        )
                    })?;
                let col_name = idx_def
                    .columns
                    .first()
                    .ok_or_else(|| format!("Index '{}' defines no columns", self.index_name))?;
                let col = self
                    .schema
                    .columns
                    .iter()
                    .find(|c| c.matches_name(col_name))
                    .ok_or_else(|| format!("Indexed column '{}' not found in schema", col_name))?;
                col.data_type.key_bounds()
            }
        };

        let rows = tx
            .index_scan(
                &self.table_name,
                &self.index_name,
                &start,
                &end,
                self.columns.as_deref(),
            )
            .map_err(|e| e.to_string())?;

        Ok(Box::new(rows.into_iter().map(Ok)))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalIndexScan: schema={:?}\n",
            "  ".repeat(indent),
            self.schema
        ));
    }
}

