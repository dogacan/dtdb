impl PhysicalProjection {
    pub fn new(source: Box<dyn PhysicalOperator>, expressions: Vec<Expr>, schema: Schema) -> Self {
        Self {
            source,
            expressions,
            schema,
        }
    }
}

impl PhysicalOperator for PhysicalProjection {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let child_iter = self.source.execute(tx, params)?;
        let child_schema = self.source.schema().clone();
        let expressions = self.expressions.clone();

        struct ProjectionIterator {
            iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            expressions: Vec<Expr>,
            schema: Schema,
        }

        impl Iterator for ProjectionIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                match self.iter.next() {
                    Some(Ok(row)) => {
                        let mut projected_vals = Vec::new();
                        for expr in &self.expressions {
                            match expr.eval(&row, &self.schema) {
                                Ok(val) => projected_vals.push(val),
                                Err(e) => return Some(Err(e)),
                            }
                        }
                        Some(Ok(Row::new(projected_vals)))
                    }
                    Some(Err(e)) => Some(Err(e)),
                    None => None,
                }
            }
        }

        Ok(Box::new(ProjectionIterator {
            iter: child_iter,
            expressions,
            schema: child_schema,
        }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalProjection: expressions={:?}\n",
            "  ".repeat(indent),
            self.expressions
        ));
        self.source.explain(indent + 1, out);
    }
}

// ==========================================
// 4. Limit Physical Operator
// ==========================================

pub struct PhysicalLimit {
    source: Box<dyn PhysicalOperator>,
    limit: Option<Expr>,
    offset: Option<Expr>,
}

impl PhysicalLimit {
    pub fn new(
        source: Box<dyn PhysicalOperator>,
        limit: Option<Expr>,
        offset: Option<Expr>,
    ) -> Self {
        Self {
            source,
            limit,
            offset,
        }
    }
}

impl PhysicalOperator for PhysicalLimit {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let child_iter = self.source.execute(tx, params)?;
        let limit = self
            .limit
            .as_ref()
            .map(|e| resolve_count_expr(e, params))
            .transpose()?;
        let offset = self
            .offset
            .as_ref()
            .map(|e| resolve_count_expr(e, params))
            .transpose()?
            .unwrap_or(0);

        struct LimitIterator {
            iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            limit: Option<usize>,
            offset: usize,
            skipped: usize,
            returned: usize,
        }

        impl Iterator for LimitIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                // Skip offset rows first
                while self.skipped < self.offset {
                    match self.iter.next() {
                        Some(Ok(_)) => {
                            self.skipped += 1;
                        }
                        Some(Err(e)) => return Some(Err(e)),
                        None => return None,
                    }
                }

                if let Some(lim) = self.limit
                    && self.returned >= lim
                {
                    return None;
                }

                match self.iter.next() {
                    Some(Ok(row)) => {
                        self.returned += 1;
                        Some(Ok(row))
                    }
                    Some(Err(e)) => Some(Err(e)),
                    None => None,
                }
            }
        }

        Ok(Box::new(LimitIterator {
            iter: child_iter,
            limit,
            offset,
            skipped: 0,
            returned: 0,
        }))
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        let limit_str = match &self.limit {
            Some(l) => format!("{:?}", l),
            None => "none".to_string(),
        };
        let offset_str = match &self.offset {
            Some(o) => format!("{:?}", o),
            None => "0".to_string(),
        };
        out.push_str(&format!(
            "{}- PhysicalLimit: limit={}, offset={}\n",
            "  ".repeat(indent),
            limit_str,
            offset_str
        ));
        self.source.explain(indent + 1, out);
    }
}

// ==========================================
// 5. Sort Physical Operator (Pipeline-Blocking)
// ==========================================
enum MergeState {
    InMemory(std::vec::IntoIter<Row>),
    External(KWayMerge<Row>),
}

pub struct PhysicalSort {
    source: Box<dyn PhysicalOperator>,
    keys: Vec<(Expr, bool)>, // (expression, asc)
    temp_dir: PathBuf,
    memory_budget: usize,
}

impl PhysicalSort {
    pub fn new(
        source: Box<dyn PhysicalOperator>,
        keys: Vec<(Expr, bool)>,
        temp_dir: PathBuf,
        memory_budget: usize,
    ) -> Self {
        Self {
            source,
            keys,
            temp_dir,
            memory_budget,
        }
    }

    fn directions(&self) -> Vec<bool> {
        self.keys.iter().map(|(_, asc)| *asc).collect()
    }
}

impl PhysicalOperator for PhysicalSort {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let child_iter = self.source.execute(tx, params)?;
        let child_schema = self.source.schema().clone();
        let directions = self.directions();
        let keys = self.keys.clone();
        let temp_dir = self.temp_dir.clone();
        let memory_budget = self.memory_budget;

        struct SortIterator {
            iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            schema: Schema,
            keys: Vec<(Expr, bool)>,
            directions: Vec<bool>,
            temp_dir: PathBuf,
            memory_budget: usize,
            merge_state: Option<MergeState>,
        }

        impl Iterator for SortIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.merge_state.is_none() {
                    let mut buffer: Vec<(Vec<DbValue>, Row)> = Vec::new();
                    let mut buffer_bytes: usize = 0;
                    let mut runs: Vec<Run<Row>> = Vec::new();

                    for row_res in self.iter.by_ref() {
                        let row = match row_res {
                            Ok(r) => r,
                            Err(e) => return Some(Err(e)),
                        };

                        let mut row_keys = Vec::with_capacity(self.keys.len());
                        for (expr, _) in &self.keys {
                            match expr.eval(&row, &self.schema) {
                                Ok(val) => row_keys.push(val),
                                Err(e) => return Some(Err(e)),
                            }
                        }

                        buffer_bytes += spill::estimate_row_size(&row_keys, &row.values);
                        buffer.push((row_keys, row));

                        if buffer_bytes >= self.memory_budget {
                            spill::sort_entries(&mut buffer, &self.directions);
                            match spill::write_run(&self.temp_dir, "sort_run", &buffer) {
                                Ok(run) => runs.push(run),
                                Err(e) => return Some(Err(e)),
                            }
                            buffer.clear();
                            buffer_bytes = 0;
                        }
                    }

                    if runs.is_empty() {
                        spill::sort_entries(&mut buffer, &self.directions);
                        self.merge_state = Some(MergeState::InMemory(
                            buffer
                                .into_iter()
                                .map(|(_, row)| row)
                                .collect::<Vec<_>>()
                                .into_iter(),
                        ));
                    } else {
                        if !buffer.is_empty() {
                            spill::sort_entries(&mut buffer, &self.directions);
                            match spill::write_run(&self.temp_dir, "sort_run", &buffer) {
                                Ok(run) => runs.push(run),
                                Err(e) => return Some(Err(e)),
                            }
                        }
                        match KWayMerge::new(
                            runs,
                            self.directions.clone(),
                            &self.temp_dir,
                            "sort_run",
                        ) {
                            Ok(merger) => self.merge_state = Some(MergeState::External(merger)),
                            Err(e) => return Some(Err(e)),
                        }
                    }
                }

                match self.merge_state.as_mut().unwrap() {
                    MergeState::InMemory(iter) => iter.next().map(Ok),
                    MergeState::External(merger) => match merger.next() {
                        Ok(Some((_, row))) => Some(Ok(row)),
                        Ok(None) => None,
                        Err(e) => Some(Err(e)),
                    },
                }
            }
        }

        Ok(Box::new(SortIterator {
            iter: child_iter,
            schema: child_schema,
            keys,
            directions,
            temp_dir,
            memory_budget,
            merge_state: None,
        }))
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        let keys_str: Vec<String> = self
            .keys
            .iter()
            .map(|(expr, asc)| format!("{:?} {}", expr, if *asc { "ASC" } else { "DESC" }))
            .collect();
        out.push_str(&format!(
            "{}- PhysicalSort: keys={:?}\n",
            "  ".repeat(indent),
            keys_str
        ));
        self.source.explain(indent + 1, out);
    }
}

// ==========================================
// 5.5. Top-N Physical Operator (Sort + Limit fusion)
// ==========================================
/// One retained row plus its evaluated sort key. `Ord` is the *natural* sort
/// order (per `directions`), so a `BinaryHeap<TopNEntry>` is a max-heap whose top
/// is the worst retained row — the one evicted when a better row arrives.
struct TopNEntry {
    keys: Vec<DbValue>,
    row: Row,
    directions: std::sync::Arc<Vec<bool>>,
}

impl Ord for TopNEntry {
    fn cmp(&self, other: &Self) -> std::cmp::Ordering {
        spill::compare_keys(&self.keys, &other.keys, &self.directions)
    }
}

impl PartialOrd for TopNEntry {
    fn partial_cmp(&self, other: &Self) -> Option<std::cmp::Ordering> {
        Some(self.cmp(other))
    }
}

impl PartialEq for TopNEntry {
    fn eq(&self, other: &Self) -> bool {
        self.cmp(other) == std::cmp::Ordering::Equal
    }
}

impl Eq for TopNEntry {}

/// Bounded top-k: where [`PhysicalSort`] materializes and sorts its entire input
/// (spilling to disk) only for an outer `LIMIT` to discard all but the first
/// rows, `PhysicalTopN` retains just the `k` best rows in a bounded max-heap of
/// capacity `k` — turning an O(n log n) external sort into an O(n log k) in-memory
/// pass with no spilling. It is produced by fusing a `LIMIT` with an
/// immediately-underlying `ORDER BY` during physical compilation, with
/// `k = OFFSET + LIMIT`; the outer [`PhysicalLimit`] still applies the actual
/// offset/limit slice over the rows emitted here (in sorted order).
///
/// Only used when `k` is small enough to stay within the memory budget — deeper
/// limits keep the spilling `PhysicalSort` + `PhysicalLimit` path instead.
pub struct PhysicalTopN {
    source: Box<dyn PhysicalOperator>,
    keys: Vec<(Expr, bool)>, // (expression, asc)
    k: usize,
}

impl PhysicalTopN {
    pub fn new(source: Box<dyn PhysicalOperator>, keys: Vec<(Expr, bool)>, k: usize) -> Self {
        Self { source, keys, k }
    }

    fn directions(&self) -> std::sync::Arc<Vec<bool>> {
        std::sync::Arc::new(self.keys.iter().map(|(_, asc)| *asc).collect())
    }
}

impl PhysicalOperator for PhysicalTopN {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let source_iter = self.source.execute(tx, params)?;
        let source_schema = self.source.schema().clone();
        let directions = self.directions();
        let k = self.k;
        let mut keys = self.keys.clone();
        for (expr, _) in &mut keys {
            expr.substitute_params(params)?;
        }

        struct TopNIterator {
            source_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            keys: Vec<(Expr, bool)>,
            source_schema: Schema,
            directions: std::sync::Arc<Vec<bool>>,
            k: usize,
            output: Option<std::vec::IntoIter<Row>>,
        }

        impl Iterator for TopNIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.output.is_none() {
                    let mut heap: std::collections::BinaryHeap<TopNEntry> =
                        std::collections::BinaryHeap::with_capacity(self.k);

                    // k == 0 retains nothing; skip draining the source entirely.
                    while self.k > 0 {
                        let row_res = match self.source_iter.next() {
                            Some(Ok(r)) => r,
                            Some(Err(e)) => return Some(Err(e)),
                            None => break,
                        };
                        let mut keys = Vec::with_capacity(self.keys.len());
                        for (expr, _) in &self.keys {
                            match expr.eval(&row_res, &self.source_schema) {
                                Ok(val) => keys.push(val),
                                Err(e) => return Some(Err(e)),
                            }
                        }
                        let entry = TopNEntry {
                            keys,
                            row: row_res,
                            directions: std::sync::Arc::clone(&self.directions),
                        };

                        if heap.len() < self.k {
                            heap.push(entry);
                        } else if let Some(mut worst) = heap.peek_mut() {
                            // Replace the worst retained row only if this one is better,
                            // re-sifting once on drop of the `PeekMut` guard.
                            if entry < *worst {
                                *worst = entry;
                            }
                        }
                    }

                    // Popping a max-heap yields worst-to-best; reverse for ascending order.
                    let mut sorted: Vec<Row> = Vec::with_capacity(heap.len());
                    while let Some(entry) = heap.pop() {
                        sorted.push(entry.row);
                    }
                    sorted.reverse();
                    self.output = Some(sorted.into_iter());
                }

                self.output.as_mut().unwrap().next().map(Ok)
            }
        }

        Ok(Box::new(TopNIterator {
            source_iter,
            keys,
            source_schema,
            directions,
            k,
            output: None,
        }))
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        let keys_str: Vec<String> = self
            .keys
            .iter()
            .map(|(expr, asc)| format!("{:?} {}", expr, if *asc { "ASC" } else { "DESC" }))
            .collect();
        out.push_str(&format!(
            "{}- PhysicalTopN: k={}, keys={:?}\n",
            "  ".repeat(indent),
            self.k,
            keys_str
        ));
        self.source.explain(indent + 1, out);
    }
}

