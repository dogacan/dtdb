// 2. Filter Physical Operator
// ==========================================
pub struct PhysicalFilter {
    source: Box<dyn PhysicalOperator>,
    predicate: Expr,
}

impl PhysicalFilter {
    pub fn new(source: Box<dyn PhysicalOperator>, predicate: Expr) -> Self {
        Self { source, predicate }
    }
}

impl PhysicalOperator for PhysicalFilter {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let child_iter = self.source.execute(tx, params)?;
        let child_schema = self.source.schema().clone();
        let predicate = self.predicate.clone();

        struct FilterIterator {
            iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            predicate: Expr,
            schema: Schema,
        }

        impl Iterator for FilterIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                loop {
                    match self.iter.next() {
                        Some(Ok(row)) => {
                            match self.predicate.eval(&row, &self.schema) {
                                Ok(res) => match res {
                                    DbValue::Bool(b) if b => return Some(Ok(row)),
                                    DbValue::Int(v) if v != 0 => return Some(Ok(row)),
                                    _ => {} // Skip row
                                },
                                Err(e) => return Some(Err(e)),
                            }
                        }
                        Some(Err(e)) => return Some(Err(e)),
                        None => return None,
                    }
                }
            }
        }

        Ok(Box::new(FilterIterator {
            iter: child_iter,
            predicate,
            schema: child_schema,
        }))
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalFilter: predicate={:?}\n",
            "  ".repeat(indent),
            self.predicate
        ));
        self.source.explain(indent + 1, out);
    }
}

