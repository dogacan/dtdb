/// PhysicalOperator defines the Volcano Iterator interface for query execution.
pub trait PhysicalOperator: Send + Sync {
    /// Spawns/opens a stateful execution iterator for this operator using the given transaction and parameters.
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String>;

    /// Returns the output Schema generated by this operator.
    fn schema(&self) -> &Schema;

    /// Formats the operator tree recursively for explanation.
    fn explain(&self, indent: usize, out: &mut String);
}

// ==========================================
// 1. SeqScan Physical Operator
// ==========================================
pub struct PhysicalSeqScan {
    schema: Schema,
    table_name: String,
    columns: Option<Vec<String>>,
    range: Option<(PlanKey, PlanKey)>,
}

impl PhysicalSeqScan {
    pub fn new(
        schema: Schema,
        table_name: String,
        columns: Option<Vec<String>>,
        range: Option<(PlanKey, PlanKey)>,
    ) -> Self {
        Self {
            schema,
            table_name,
            columns,
            range,
        }
    }
}

impl PhysicalOperator for PhysicalSeqScan {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let (start, end) = match &self.range {
            Some((start_key, end_key)) => (start_key.resolve(params)?, end_key.resolve(params)?),
            None => self
                .schema
                .primary_key_bounds()
                .map_err(|e| e.to_string())?,
        };

        let iter = tx
            .scan_iter(&self.table_name, &start, &end, self.columns.as_deref())
            .map_err(|e| e.to_string())?;

        struct SeqScanIterator {
            iter: dtdb_relational::TransactionScanIterator,
        }

        impl Iterator for SeqScanIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                match self.iter.next() {
                    Ok(Some(row)) => Some(Ok(row)),
                    Ok(None) => None,
                    Err(e) => Some(Err(e.to_string())),
                }
            }
        }

        Ok(Box::new(SeqScanIterator { iter }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalSeqScan: schema={:?}\n",
            "  ".repeat(indent),
            self.schema
        ));
    }
}

