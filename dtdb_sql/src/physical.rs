pub struct PhysicalProjection {
    source: Box<dyn PhysicalOperator>,
    expressions: Vec<Expr>,
    schema: Schema,
}

impl PhysicalProjection {
    pub fn new(source: Box<dyn PhysicalOperator>, expressions: Vec<Expr>, schema: Schema) -> Self {
        Self {
            source,
            expressions,
            schema,
        }
    }
}

impl PhysicalOperator for PhysicalProjection {
    fn next(&mut self) -> Result<Option<Row>, String> {
        if let Some(row) = self.source.next()? {
            let mut projected_vals = Vec::new();
            let source_schema = self.source.schema();
            for expr in &self.expressions {
                projected_vals.push(expr.eval(&row, source_schema)?);
            }
            Ok(Some(Row::new(projected_vals)))
        } else {
            Ok(None)
        }
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalProjection: expressions={:?}\n",
            "  ".repeat(indent),
            self.expressions
        ));
        self.source.explain(indent + 1, out);
    }
}

// ==========================================
// 4. Limit Physical Operator
// ==========================================
pub struct PhysicalLimit {
    source: Box<dyn PhysicalOperator>,
    limit: Option<usize>,
    offset: usize,
    skipped: usize,
    returned: usize,
}

impl PhysicalLimit {
    pub fn new(source: Box<dyn PhysicalOperator>, limit: Option<usize>, offset: usize) -> Self {
        Self {
            source,
            limit,
            offset,
            skipped: 0,
            returned: 0,
        }
    }
}

impl PhysicalOperator for PhysicalLimit {
    fn next(&mut self) -> Result<Option<Row>, String> {
        // Skip offset rows first
        while self.skipped < self.offset {
            if self.source.next()?.is_none() {
                return Ok(None);
            }
            self.skipped += 1;
        }

        if let Some(lim) = self.limit
            && self.returned >= lim
        {
            return Ok(None);
        }

        if let Some(row) = self.source.next()? {
            self.returned += 1;
            Ok(Some(row))
        } else {
            Ok(None)
        }
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        let limit_str = match self.limit {
            Some(l) => l.to_string(),
            None => "none".to_string(),
        };
        out.push_str(&format!(
            "{}- PhysicalLimit: limit={}, offset={}\n",
            "  ".repeat(indent),
            limit_str,
            self.offset
        ));
        self.source.explain(indent + 1, out);
    }
}

