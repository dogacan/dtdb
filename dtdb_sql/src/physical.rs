// Aggregation State Accumulators
// ==========================================
#[derive(Clone, serde::Serialize, serde::Deserialize)]
enum Accumulator {
    Count {
        count: i64,
    },
    // Track integer and floating-point running totals separately so SUM(int_col)
    // can finalize as Int when no Float input is ever observed, matching the
    // schema declared by the logical planner. We only fall back to Float if a
    // Float input appears or if the integer accumulator would overflow.
    Sum {
        int_sum: Option<i64>,
        float_sum: Option<f64>,
        // Stringified for spill serialization: rust_decimal's default serde uses
        // `deserialize_any`, which postcard (the spill format) cannot decode.
        #[serde(with = "dtdb_storage::decimal_serde_option")]
        decimal_sum: Option<rust_decimal::Decimal>,
    },
    Min {
        min: Option<DbValue>,
    },
    Max {
        max: Option<DbValue>,
    },
    Avg {
        sum: f64,
        count: i64,
        #[serde(with = "dtdb_storage::decimal_serde_option")]
        decimal_sum: Option<rust_decimal::Decimal>,
    },
    // DISTINCT aggregate (COUNT/SUM/AVG DISTINCT). Inputs are collected into
    // `seen`, deduplicated by value, and the wrapped `inner` aggregate is applied
    // to the distinct set only at finalize time. Deferring aggregation keeps
    // merging of spilled partial groups a simple set union: the same value may
    // appear in several runs of one group, so partial inner results cannot be
    // combined directly without double counting.
    Distinct {
        seen: HashSet<DbValue>,
        inner: Box<Accumulator>,
    },
}

/// Builds a fresh zeroed accumulator for a single aggregate expression, wrapping
/// it in a `Distinct` layer when the call used the `DISTINCT` quantifier. MIN/MAX
/// are idempotent under duplication, so DISTINCT is a no-op there and skipped.
fn make_accumulator(aggr: &AggregateExpr) -> Accumulator {
    let (base, distinct) = match aggr {
        AggregateExpr::Count { distinct, .. } => (Accumulator::Count { count: 0 }, *distinct),
        AggregateExpr::Sum { distinct, .. } => (
            Accumulator::Sum {
                int_sum: None,
                float_sum: None,
                decimal_sum: None,
            },
            *distinct,
        ),
        AggregateExpr::Avg { distinct, .. } => (
            Accumulator::Avg {
                sum: 0.0,
                count: 0,
                decimal_sum: None,
            },
            *distinct,
        ),
        AggregateExpr::Min { .. } => (Accumulator::Min { min: None }, false),
        AggregateExpr::Max { .. } => (Accumulator::Max { max: None }, false),
    };
    if distinct {
        Accumulator::Distinct {
            seen: HashSet::new(),
            inner: Box::new(base),
        }
    } else {
        base
    }
}

/// Creates a fresh set of zeroed accumulators matching the given aggregate exprs.
fn new_accumulators(aggrs: &[AggregateExpr]) -> Vec<Accumulator> {
    aggrs.iter().map(make_accumulator).collect()
}

/// Builds an output row from group keys followed by each finalized aggregate.
fn finalize_group(keys: Vec<DbValue>, accs: Vec<Accumulator>) -> Result<Row, String> {
    let mut row_vals = keys;
    for acc in accs {
        row_vals.push(acc.finalize()?);
    }
    Ok(Row::new(row_vals))
}

impl Accumulator {
    fn update(&mut self, val: &DbValue) -> Result<(), String> {
        if matches!(val, DbValue::Null) {
            return Ok(()); // Ignore NULL values for all aggregates
        }
        match self {
            // Defer the underlying aggregation to finalize; here we only record the
            // distinct input values. The NULL guard above already excludes NULLs.
            Accumulator::Distinct { seen, .. } => {
                seen.insert(val.clone());
            }
            Accumulator::Count { count } => {
                *count += 1;
            }
            Accumulator::Sum {
                int_sum,
                float_sum,
                decimal_sum,
            } => match val {
                DbValue::Decimal(v) => {
                    if let Some(dec) = decimal_sum {
                        *decimal_sum = Some(*dec + *v);
                    } else {
                        let current = int_sum.take().unwrap_or(0);
                        *decimal_sum = Some(rust_decimal::Decimal::from(current) + *v);
                    }
                }
                DbValue::Int(v) => {
                    if let Some(dec) = decimal_sum {
                        *decimal_sum = Some(*dec + rust_decimal::Decimal::from(*v));
                    } else if float_sum.is_some() {
                        *float_sum.as_mut().unwrap() += *v as f64;
                    } else {
                        let current = int_sum.unwrap_or(0);
                        match current.checked_add(*v) {
                            Some(new_sum) => *int_sum = Some(new_sum),
                            None => {
                                let promoted = current as f64 + *v as f64;
                                *int_sum = None;
                                *float_sum = Some(promoted);
                            }
                        }
                    }
                }
                DbValue::Float(v) => {
                    if let Some(dec) = decimal_sum.take() {
                        let dec_f = dec.to_f64().unwrap_or(0.0);
                        *float_sum = Some(dec_f + *v);
                    } else {
                        let promoted =
                            float_sum.unwrap_or(0.0) + int_sum.take().unwrap_or(0) as f64;
                        *float_sum = Some(promoted + *v);
                    }
                }
                other => {
                    return Err(format!(
                        "Cannot compute SUM on non-numeric value {:?}",
                        other
                    ));
                }
            },
            Accumulator::Min { min } => match min {
                Some(m) => {
                    let ord = compare_values(val, m)?;
                    if ord == std::cmp::Ordering::Less {
                        *min = Some(val.clone());
                    }
                }
                None => *min = Some(val.clone()),
            },
            Accumulator::Max { max } => match max {
                Some(m) => {
                    let ord = compare_values(val, m)?;
                    if ord == std::cmp::Ordering::Greater {
                        *max = Some(val.clone());
                    }
                }
                None => *max = Some(val.clone()),
            },
            Accumulator::Avg {
                sum,
                count,
                decimal_sum,
            } => {
                match val {
                    DbValue::Decimal(v) => {
                        if let Some(dec) = decimal_sum {
                            *decimal_sum = Some(*dec + *v);
                        } else {
                            if *count > 0 {
                                if let Some(dec_prev) = rust_decimal::Decimal::from_f64(*sum) {
                                    *decimal_sum = Some(dec_prev + *v);
                                } else {
                                    *sum += v.to_f64().unwrap_or(0.0);
                                }
                            } else {
                                *decimal_sum = Some(*v);
                            }
                        }
                    }
                    DbValue::Int(v) => {
                        if let Some(dec) = decimal_sum {
                            *decimal_sum = Some(*dec + rust_decimal::Decimal::from(*v));
                        } else {
                            *sum += *v as f64;
                        }
                    }
                    DbValue::Float(v) => {
                        if let Some(dec) = decimal_sum.take() {
                            *sum = dec.to_f64().unwrap_or(0.0) + *v;
                        } else {
                            *sum += *v;
                        }
                    }
                    other => {
                        return Err(format!(
                            "Cannot compute AVG on non-numeric value {:?}",
                            other
                        ));
                    }
                }
                *count += 1;
            }
        }
        Ok(())
    }

    /// Combines a partial accumulator (from a spilled run) into this one. Both
    /// must be the same variant, which holds because they aggregate the same
    /// group across runs.
    fn merge(&mut self, other: Accumulator) -> Result<(), String> {
        match (self, other) {
            (Accumulator::Count { count }, Accumulator::Count { count: o }) => {
                *count += o;
            }
            (
                Accumulator::Sum {
                    int_sum,
                    float_sum,
                    decimal_sum,
                },
                Accumulator::Sum {
                    int_sum: o_int,
                    float_sum: o_float,
                    decimal_sum: o_dec,
                },
            ) => {
                if decimal_sum.is_some() || o_dec.is_some() {
                    let a = decimal_sum.unwrap_or(rust_decimal::Decimal::ZERO)
                        + rust_decimal::Decimal::from(int_sum.take().unwrap_or(0));
                    let b = o_dec.unwrap_or(rust_decimal::Decimal::ZERO)
                        + rust_decimal::Decimal::from(o_int.unwrap_or(0));
                    *decimal_sum = Some(a + b);
                } else if float_sum.is_some() || o_float.is_some() {
                    let a = float_sum.unwrap_or(0.0) + int_sum.take().unwrap_or(0) as f64;
                    let b = o_float.unwrap_or(0.0) + o_int.unwrap_or(0) as f64;
                    *float_sum = Some(a + b);
                } else {
                    match (*int_sum, o_int) {
                        (None, None) => {}
                        (Some(a), None) => *int_sum = Some(a),
                        (None, Some(b)) => *int_sum = Some(b),
                        (Some(a), Some(b)) => match a.checked_add(b) {
                            Some(s) => *int_sum = Some(s),
                            None => {
                                *int_sum = None;
                                *float_sum = Some(a as f64 + b as f64);
                            }
                        },
                    }
                }
            }
            (Accumulator::Min { min }, Accumulator::Min { min: o }) => {
                if let Some(v) = o {
                    match min {
                        Some(cur) if compare_values(&v, cur)? != std::cmp::Ordering::Less => {}
                        _ => *min = Some(v),
                    }
                }
            }
            (Accumulator::Max { max }, Accumulator::Max { max: o }) => {
                if let Some(v) = o {
                    match max {
                        Some(cur) if compare_values(&v, cur)? != std::cmp::Ordering::Greater => {}
                        _ => *max = Some(v),
                    }
                }
            }
            (
                Accumulator::Avg {
                    sum,
                    count,
                    decimal_sum,
                },
                Accumulator::Avg {
                    sum: o_sum,
                    count: o_count,
                    decimal_sum: o_dec,
                },
            ) => {
                if decimal_sum.is_some() || o_dec.is_some() {
                    let a = decimal_sum.unwrap_or(rust_decimal::Decimal::ZERO);
                    let b = o_dec.unwrap_or(rust_decimal::Decimal::ZERO);
                    *decimal_sum = Some(a + b);
                } else {
                    *sum += o_sum;
                }
                *count += o_count;
            }
            // Partial distinct groups from different spilled runs may share values,
            // so the inner aggregate is rebuilt from the union at finalize; merging
            // is just the set union of observed values.
            (Accumulator::Distinct { seen, .. }, Accumulator::Distinct { seen: o_seen, .. }) => {
                seen.extend(o_seen);
            }
            _ => return Err("Cannot merge accumulators of different kinds".to_string()),
        }
        Ok(())
    }

    fn finalize(&self) -> Result<DbValue, String> {
        let val = match self {
            Accumulator::Count { count } => DbValue::Int(*count),
            Accumulator::Sum {
                int_sum,
                float_sum,
                decimal_sum,
            } => {
                if let Some(dec) = decimal_sum {
                    DbValue::Decimal(*dec)
                } else {
                    match (float_sum, int_sum) {
                        (Some(f), _) => DbValue::Float(*f),
                        (None, Some(i)) => DbValue::Int(*i),
                        (None, None) => DbValue::Null,
                    }
                }
            }
            Accumulator::Min { min } => min.clone().unwrap_or(DbValue::Null),
            Accumulator::Max { max } => max.clone().unwrap_or(DbValue::Null),
            Accumulator::Avg {
                sum,
                count,
                decimal_sum,
            } => {
                if *count == 0 {
                    DbValue::Null
                } else if let Some(dec) = decimal_sum {
                    let count_dec = rust_decimal::Decimal::from(*count);
                    DbValue::Decimal(*dec / count_dec)
                } else {
                    DbValue::Float(*sum / (*count as f64))
                }
            }
            // Replay the deduplicated values through a fresh copy of the wrapped
            // aggregate. Set iteration order is unspecified, which is fine: the
            // wrapped aggregates here (COUNT/SUM/AVG) are order-insensitive.
            Accumulator::Distinct { seen, inner } => {
                let mut acc = (**inner).clone();
                for v in seen {
                    acc.update(v)?;
                }
                acc.finalize()?
            }
        };
        Ok(val)
    }
}

