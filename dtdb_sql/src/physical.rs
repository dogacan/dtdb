// 6.5. CrossJoin Physical Operator (Cartesian Product)
// ==========================================
pub struct PhysicalCrossJoin {
    left: Box<dyn PhysicalOperator>,
    right: Box<dyn PhysicalOperator>,
    schema: Schema,
}

impl PhysicalCrossJoin {
    pub fn new(
        left: Box<dyn PhysicalOperator>,
        right: Box<dyn PhysicalOperator>,
        schema: Schema,
    ) -> Self {
        Self {
            left,
            right,
            schema,
        }
    }
}

impl PhysicalOperator for PhysicalCrossJoin {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let left_iter = self.left.execute(tx, params)?;
        let right_iter = self.right.execute(tx, params)?;

        struct CrossJoinIterator {
            left_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            right_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            right_rows: Option<Vec<Row>>,
            current_left_row: Option<Row>,
            right_index: usize,
        }

        impl Iterator for CrossJoinIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                // Build phase: read all right rows into memory
                if self.right_rows.is_none() {
                    let mut rows = Vec::new();
                    for row_res in &mut self.right_iter {
                        match row_res {
                            Ok(row) => rows.push(row),
                            Err(e) => return Some(Err(e)),
                        }
                    }
                    self.right_rows = Some(rows);
                }

                let right_rows = self.right_rows.as_ref().unwrap();
                if right_rows.is_empty() {
                    return None;
                }

                loop {
                    if self.current_left_row.is_none() {
                        match self.left_iter.next() {
                            Some(Ok(row)) => {
                                self.current_left_row = Some(row);
                                self.right_index = 0;
                            }
                            Some(Err(e)) => return Some(Err(e)),
                            None => return None,
                        }
                    }

                    let left_row = self.current_left_row.as_ref().unwrap();
                    if self.right_index < right_rows.len() {
                        let right_row = &right_rows[self.right_index];
                        self.right_index += 1;

                        let mut merged_values = left_row.values.clone();
                        merged_values.extend(right_row.values.clone());
                        return Some(Ok(Row::new(merged_values)));
                    } else {
                        self.current_left_row = None;
                    }
                }
            }
        }

        Ok(Box::new(CrossJoinIterator {
            left_iter,
            right_iter,
            right_rows: None,
            current_left_row: None,
            right_index: 0,
        }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!("{}- PhysicalCrossJoin\n", "  ".repeat(indent)));
        out.push_str(&format!("{}  left:\n", "  ".repeat(indent)));
        self.left.explain(indent + 2, out);
        out.push_str(&format!("{}  right:\n", "  ".repeat(indent)));
        self.right.explain(indent + 2, out);
    }
}

// ==========================================
// 7. HashAggregate Physical Operator (Pipeline-Blocking)
// ==========================================
pub struct PhysicalHashAggregate {
    source: Box<dyn PhysicalOperator>,
    group_by: Vec<Expr>,
    aggrs: Vec<AggregateExpr>,
    schema: Schema,
    temp_dir: PathBuf,
    memory_budget: usize,
}

/// Output state of a hash aggregate once its build phase has run: either all groups
/// fit in memory, or partial groups were spilled and are streamed back via merge.
enum AggOutput {
    InMemory(std::vec::IntoIter<Row>),
    Merge(AggMerge),
}

/// Streams finalized rows out of spilled partial-aggregate runs, combining the
/// partial accumulators of equal group keys (which are adjacent after merge).
struct AggMerge {
    merger: KWayMerge<Vec<Accumulator>>,
    current: Option<(Vec<DbValue>, Vec<Accumulator>)>,
}

impl AggMerge {
    fn next(&mut self) -> Result<Option<Row>, String> {
        loop {
            match self.merger.next()? {
                Some((key, accs)) => match &mut self.current {
                    Some((cur_key, cur_accs)) if *cur_key == key => {
                        for (acc, partial) in cur_accs.iter_mut().zip(accs) {
                            acc.merge(partial)?;
                        }
                    }
                    _ => {
                        if let Some((k, a)) = self.current.replace((key, accs)) {
                            return Ok(Some(finalize_group(k, a)?));
                        }
                    }
                },
                None => {
                    return match self.current.take() {
                        Some((k, a)) => Ok(Some(finalize_group(k, a)?)),
                        None => Ok(None),
                    };
                }
            }
        }
    }
}

impl PhysicalHashAggregate {
    pub fn new(
        source: Box<dyn PhysicalOperator>,
        group_by: Vec<Expr>,
        aggrs: Vec<AggregateExpr>,
        schema: Schema,
        temp_dir: PathBuf,
        memory_budget: usize,
    ) -> Self {
        Self {
            source,
            group_by,
            aggrs,
            schema,
            temp_dir,
            memory_budget,
        }
    }
}

impl PhysicalOperator for PhysicalHashAggregate {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let source_iter = self.source.execute(tx, params)?;
        let source_schema = self.source.schema().clone();

        let mut group_by = self.group_by.clone();
        for expr in &mut group_by {
            expr.substitute_params(params)?;
        }
        let mut aggrs = self.aggrs.clone();
        for aggr in &mut aggrs {
            match aggr {
                AggregateExpr::Count { expr, .. }
                | AggregateExpr::Sum { expr, .. }
                | AggregateExpr::Min { expr, .. }
                | AggregateExpr::Max { expr, .. }
                | AggregateExpr::Avg { expr, .. } => {
                    expr.substitute_params(params)?;
                }
            }
        }

        struct HashAggregateIterator {
            source_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            source_schema: Schema,
            group_by: Vec<Expr>,
            aggrs: Vec<AggregateExpr>,
            temp_dir: PathBuf,
            memory_budget: usize,
            output: Option<AggOutput>,
        }

        impl HashAggregateIterator {
            fn spill_groups(
                &self,
                groups: &mut HashMap<Vec<DbValue>, Vec<Accumulator>>,
                runs: &mut Vec<Run<Vec<Accumulator>>>,
            ) -> Result<(), String> {
                let directions = vec![true; self.group_by.len()];
                let mut entries: Vec<(Vec<DbValue>, Vec<Accumulator>)> = groups.drain().collect();
                spill::sort_entries(&mut entries, &directions);
                runs.push(spill::write_run(&self.temp_dir, "agg_run", &entries)?);
                Ok(())
            }
        }

        impl Iterator for HashAggregateIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.output.is_none() {
                    let mut groups: HashMap<Vec<DbValue>, Vec<Accumulator>> = HashMap::new();
                    let mut buffer_bytes: usize = 0;
                    let mut runs: Vec<Run<Vec<Accumulator>>> = Vec::new();
                    let acc_overhead = self.aggrs.len() * std::mem::size_of::<Accumulator>();

                    while let Some(row_res) = self.source_iter.next() {
                        let row = match row_res {
                            Ok(r) => r,
                            Err(e) => return Some(Err(e)),
                        };

                        let mut group_vals = Vec::with_capacity(self.group_by.len());
                        for expr in &self.group_by {
                            match expr.eval(&row, &self.source_schema) {
                                Ok(val) => group_vals.push(val),
                                Err(e) => return Some(Err(e)),
                            }
                        }

                        let added = if groups.contains_key(&group_vals) {
                            0
                        } else {
                            spill::estimate_row_size(&group_vals, &[]) + acc_overhead
                        };
                        let accumulators = groups
                            .entry(group_vals)
                            .or_insert_with(|| new_accumulators(&self.aggrs));

                        for (idx, aggr) in self.aggrs.iter().enumerate() {
                            let val = match aggr {
                                AggregateExpr::Count { expr, .. }
                                | AggregateExpr::Sum { expr, .. }
                                | AggregateExpr::Min { expr, .. }
                                | AggregateExpr::Max { expr, .. }
                                | AggregateExpr::Avg { expr, .. } => {
                                    match expr.eval(&row, &self.source_schema) {
                                        Ok(v) => v,
                                        Err(e) => return Some(Err(e)),
                                    }
                                }
                            };
                            if let Err(e) = accumulators[idx].update(&val) {
                                return Some(Err(e));
                            }
                        }

                        buffer_bytes += added;
                        if buffer_bytes >= self.memory_budget && !self.group_by.is_empty() {
                            if let Err(e) = self.spill_groups(&mut groups, &mut runs) {
                                return Some(Err(e));
                            }
                            buffer_bytes = 0;
                        }
                    }

                    if runs.is_empty() {
                        if self.group_by.is_empty() && groups.is_empty() {
                            groups.insert(Vec::new(), new_accumulators(&self.aggrs));
                        }
                        let output_rows: Vec<Row> = match groups
                            .into_iter()
                            .map(|(keys, accs)| finalize_group(keys, accs))
                            .collect::<Result<_, String>>()
                        {
                            Ok(rows) => rows,
                            Err(e) => return Some(Err(e)),
                        };
                        self.output = Some(AggOutput::InMemory(output_rows.into_iter()));
                    } else {
                        if !groups.is_empty() {
                            let res = self.spill_groups(&mut groups, &mut runs);
                            if let Err(e) = res {
                                return Some(Err(e));
                            }
                        }
                        let merger = match KWayMerge::new(
                            runs,
                            vec![true; self.group_by.len()],
                            &self.temp_dir,
                            "agg_run",
                        ) {
                            Ok(m) => m,
                            Err(e) => return Some(Err(e)),
                        };
                        self.output = Some(AggOutput::Merge(AggMerge {
                            merger,
                            current: None,
                        }));
                    }
                }

                match self.output.as_mut().unwrap() {
                    AggOutput::InMemory(iter) => iter.next().map(Ok),
                    AggOutput::Merge(merge) => match merge.next() {
                        Ok(Some(row)) => Some(Ok(row)),
                        Ok(None) => None,
                        Err(e) => Some(Err(e)),
                    },
                }
            }
        }

        Ok(Box::new(HashAggregateIterator {
            source_iter,
            source_schema,
            group_by,
            aggrs,
            temp_dir: self.temp_dir.clone(),
            memory_budget: self.memory_budget,
            output: None,
        }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalHashAggregate: group_by={:?}, aggrs={:?}\n",
            "  ".repeat(indent),
            self.group_by,
            self.aggrs
        ));
        self.source.explain(indent + 1, out);
    }
}

// ==========================================
// 7.5. SortedAggregate Physical Operator (Streaming)
// ==========================================
pub struct PhysicalSortedAggregate {
    source: Box<dyn PhysicalOperator>,
    group_by: Vec<Expr>,
    aggrs: Vec<AggregateExpr>,
    schema: Schema,
}

impl PhysicalSortedAggregate {
    pub fn new(
        source: Box<dyn PhysicalOperator>,
        group_by: Vec<Expr>,
        aggrs: Vec<AggregateExpr>,
        schema: Schema,
    ) -> Self {
        Self {
            source,
            group_by,
            aggrs,
            schema,
        }
    }
}

impl PhysicalOperator for PhysicalSortedAggregate {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let source_iter = self.source.execute(tx, params)?;
        let source_schema = self.source.schema().clone();

        let mut group_by = self.group_by.clone();
        for expr in &mut group_by {
            expr.substitute_params(params)?;
        }
        let mut aggrs = self.aggrs.clone();
        for aggr in &mut aggrs {
            match aggr {
                AggregateExpr::Count { expr, .. }
                | AggregateExpr::Sum { expr, .. }
                | AggregateExpr::Min { expr, .. }
                | AggregateExpr::Max { expr, .. }
                | AggregateExpr::Avg { expr, .. } => {
                    expr.substitute_params(params)?;
                }
            }
        }

        struct SortedAggregateIterator {
            source_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            source_schema: Schema,
            group_by: Vec<Expr>,
            aggrs: Vec<AggregateExpr>,
            active_group_keys: Option<Vec<DbValue>>,
            active_accumulators: Vec<Accumulator>,
            next_row: Option<Row>,
            source_exhausted: bool,
        }

        impl Iterator for SortedAggregateIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.next_row.is_none() && !self.source_exhausted {
                    match self.source_iter.next() {
                        Some(Ok(row)) => {
                            self.next_row = Some(row);
                        }
                        Some(Err(e)) => return Some(Err(e)),
                        None => {
                            self.source_exhausted = true;
                            if self.group_by.is_empty() && self.active_group_keys.is_none() {
                                self.active_group_keys = Some(Vec::new());
                                self.active_accumulators = new_accumulators(&self.aggrs);
                            }
                        }
                    }
                }

                loop {
                    let row = match self.next_row.take() {
                        Some(r) => r,
                        None => {
                            if let Some(keys) = self.active_group_keys.take() {
                                let mut row_vals = keys;
                                for acc in self.active_accumulators.drain(..) {
                                    match acc.finalize() {
                                        Ok(val) => row_vals.push(val),
                                        Err(e) => return Some(Err(e)),
                                    }
                                }
                                return Some(Ok(Row::new(row_vals)));
                            }
                            return None;
                        }
                    };

                    let mut group_vals = Vec::with_capacity(self.group_by.len());
                    for expr in &self.group_by {
                        match expr.eval(&row, &self.source_schema) {
                            Ok(val) => group_vals.push(val),
                            Err(e) => return Some(Err(e)),
                        }
                    }

                    if let Some(active_keys) = &self.active_group_keys {
                        if group_vals == *active_keys {
                            for (idx, aggr) in self.aggrs.iter().enumerate() {
                                let val = match aggr {
                                    AggregateExpr::Count { expr, .. }
                                    | AggregateExpr::Sum { expr, .. }
                                    | AggregateExpr::Min { expr, .. }
                                    | AggregateExpr::Max { expr, .. }
                                    | AggregateExpr::Avg { expr, .. } => {
                                        match expr.eval(&row, &self.source_schema) {
                                            Ok(v) => v,
                                            Err(e) => return Some(Err(e)),
                                        }
                                    }
                                };
                                if let Err(e) = self.active_accumulators[idx].update(&val) {
                                    return Some(Err(e));
                                }
                            }

                            match self.source_iter.next() {
                                Some(Ok(row)) => {
                                    self.next_row = Some(row);
                                }
                                Some(Err(e)) => return Some(Err(e)),
                                None => {
                                    self.source_exhausted = true;
                                }
                            }
                        } else {
                            self.next_row = Some(row);

                            let keys = self.active_group_keys.take().unwrap();
                            let mut row_vals = keys;
                            for acc in self.active_accumulators.drain(..) {
                                match acc.finalize() {
                                    Ok(val) => row_vals.push(val),
                                    Err(e) => return Some(Err(e)),
                                }
                            }
                            return Some(Ok(Row::new(row_vals)));
                        }
                    } else {
                        self.active_group_keys = Some(group_vals);
                        self.active_accumulators = new_accumulators(&self.aggrs);

                        for (idx, aggr) in self.aggrs.iter().enumerate() {
                            let val = match aggr {
                                AggregateExpr::Count { expr, .. }
                                | AggregateExpr::Sum { expr, .. }
                                | AggregateExpr::Min { expr, .. }
                                | AggregateExpr::Max { expr, .. }
                                | AggregateExpr::Avg { expr, .. } => {
                                    match expr.eval(&row, &self.source_schema) {
                                        Ok(v) => v,
                                        Err(e) => return Some(Err(e)),
                                    }
                                }
                            };
                            if let Err(e) = self.active_accumulators[idx].update(&val) {
                                return Some(Err(e));
                            }
                        }

                        match self.source_iter.next() {
                            Some(Ok(row)) => {
                                self.next_row = Some(row);
                            }
                            Some(Err(e)) => return Some(Err(e)),
                            None => {
                                self.source_exhausted = true;
                            }
                        }
                    }
                }
            }
        }

        Ok(Box::new(SortedAggregateIterator {
            source_iter,
            source_schema,
            group_by,
            aggrs,
            active_group_keys: None,
            active_accumulators: Vec::new(),
            next_row: None,
            source_exhausted: false,
        }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalSortedAggregate: group_by={:?}, aggrs={:?}\n",
            "  ".repeat(indent),
            self.group_by,
            self.aggrs
        ));
        self.source.explain(indent + 1, out);
    }
}

