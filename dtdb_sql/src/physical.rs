/// A peekable stream of rows in total-order, produced by externally sorting a child
/// operator. Memory is bounded by spilling sorted runs; `head` holds the current row.
struct SortedRowStream {
    inner: SortedStreamInner,
    head: Option<Vec<DbValue>>,
}

enum SortedStreamInner {
    InMemory(std::vec::IntoIter<Vec<DbValue>>),
    External(KWayMerge<()>),
}

impl SortedRowStream {
    fn build(
        source: &mut dyn Iterator<Item = Result<Row, String>>,
        source_schema: &Schema,
        temp_dir: &std::path::Path,
        memory_budget: usize,
    ) -> Result<Self, String> {
        let directions = vec![true; source_schema.columns.len()];
        let mut buffer: Vec<(Vec<DbValue>, ())> = Vec::new();
        let mut buffer_bytes: usize = 0;
        let mut runs: Vec<Run<()>> = Vec::new();

        for row_res in source {
            let row = row_res?;
            let key = row.values;
            buffer_bytes += spill::estimate_row_size(&key, &[]);
            buffer.push((key, ()));
            if buffer_bytes >= memory_budget {
                spill::sort_entries(&mut buffer, &directions);
                runs.push(spill::write_run(temp_dir, "setop_run", &buffer)?);
                buffer.clear();
                buffer_bytes = 0;
            }
        }

        let inner = if runs.is_empty() {
            spill::sort_entries(&mut buffer, &directions);
            SortedStreamInner::InMemory(
                buffer
                    .into_iter()
                    .map(|(k, _)| k)
                    .collect::<Vec<_>>()
                    .into_iter(),
            )
        } else {
            if !buffer.is_empty() {
                spill::sort_entries(&mut buffer, &directions);
                runs.push(spill::write_run(temp_dir, "setop_run", &buffer)?);
            }
            SortedStreamInner::External(KWayMerge::new(runs, directions, temp_dir, "setop_run")?)
        };

        let mut stream = Self { inner, head: None };
        stream.advance()?;
        Ok(stream)
    }

    fn advance(&mut self) -> Result<(), String> {
        self.head = match &mut self.inner {
            SortedStreamInner::InMemory(iter) => iter.next(),
            SortedStreamInner::External(merger) => merger.next()?.map(|(k, _)| k),
        };
        Ok(())
    }

    fn peek(&self) -> Option<&Vec<DbValue>> {
        self.head.as_ref()
    }

    /// Consumes and counts the rows at the head equal to `key`, advancing past them.
    fn consume_equal(&mut self, key: &[DbValue]) -> Result<usize, String> {
        let mut count = 0;
        while let Some(head) = self.head.as_deref() {
            if compare_rows(head, key) == std::cmp::Ordering::Equal {
                count += 1;
                self.advance()?;
            } else {
                break;
            }
        }
        Ok(count)
    }
}

/// Total-order comparison of two whole rows (all columns ascending).
fn compare_rows(a: &[DbValue], b: &[DbValue]) -> std::cmp::Ordering {
    for (x, y) in a.iter().zip(b.iter()) {
        let ord = spill::total_compare(x, y);
        if ord != std::cmp::Ordering::Equal {
            return ord;
        }
    }
    a.len().cmp(&b.len())
}

pub struct PhysicalSetOp {
    left: Box<dyn PhysicalOperator>,
    right: Box<dyn PhysicalOperator>,
    op: SetOpType,
    all: bool,
    schema: Schema,
    temp_dir: PathBuf,
    memory_budget: usize,
}

impl PhysicalSetOp {
    pub fn new(
        left: Box<dyn PhysicalOperator>,
        right: Box<dyn PhysicalOperator>,
        op: SetOpType,
        all: bool,
        schema: Schema,
        temp_dir: PathBuf,
        memory_budget: usize,
    ) -> Self {
        Self {
            left,
            right,
            op,
            all,
            schema,
            temp_dir,
            memory_budget,
        }
    }
}

/// Number of times the row for the current key should be emitted, given the
/// occurrence counts on each side and the operation's multiset semantics.
fn set_op_emit_count(op: &SetOpType, all: bool, left_count: usize, right_count: usize) -> usize {
    match op {
        SetOpType::Union => {
            if all {
                left_count + right_count
            } else {
                usize::from(left_count + right_count > 0)
            }
        }
        SetOpType::Intersect => {
            if all {
                left_count.min(right_count)
            } else {
                usize::from(left_count > 0 && right_count > 0)
            }
        }
        SetOpType::Except => {
            if all {
                left_count.saturating_sub(right_count)
            } else {
                usize::from(left_count > 0 && right_count == 0)
            }
        }
    }
}

impl PhysicalOperator for PhysicalSetOp {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let left_iter = self.left.execute(tx, params)?;
        let right_iter = self.right.execute(tx, params)?;
        let left_schema = self.left.schema().clone();
        let right_schema = self.right.schema().clone();

        struct SetOpIterator {
            left_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            right_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            left_schema: Schema,
            right_schema: Schema,
            op: SetOpType,
            all: bool,
            temp_dir: PathBuf,
            memory_budget: usize,
            streams: Option<(SortedRowStream, SortedRowStream)>,
            pending: std::collections::VecDeque<Vec<DbValue>>,
        }

        impl Iterator for SetOpIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.streams.is_none() {
                    let left = match SortedRowStream::build(
                        &mut *self.left_iter,
                        &self.left_schema,
                        &self.temp_dir,
                        self.memory_budget,
                    ) {
                        Ok(s) => s,
                        Err(e) => return Some(Err(e)),
                    };
                    let right = match SortedRowStream::build(
                        &mut *self.right_iter,
                        &self.right_schema,
                        &self.temp_dir,
                        self.memory_budget,
                    ) {
                        Ok(s) => s,
                        Err(e) => return Some(Err(e)),
                    };
                    self.streams = Some((left, right));
                }

                let op = self.op;
                let all = self.all;
                let (left, right) = self.streams.as_mut().unwrap();

                loop {
                    if let Some(row) = self.pending.pop_front() {
                        return Some(Ok(Row::new(row)));
                    }

                    // Pick the smaller of the two current heads as the next group key.
                    let key = match (left.peek(), right.peek()) {
                        (None, None) => return None,
                        (Some(l), None) => l.clone(),
                        (None, Some(r)) => r.clone(),
                        (Some(l), Some(r)) => {
                            if compare_rows(l, r) == std::cmp::Ordering::Greater {
                                r.clone()
                            } else {
                                l.clone()
                            }
                        }
                    };

                    let left_count = match left.consume_equal(&key) {
                        Ok(c) => c,
                        Err(e) => return Some(Err(e)),
                    };
                    let right_count = match right.consume_equal(&key) {
                        Ok(c) => c,
                        Err(e) => return Some(Err(e)),
                    };

                    let emit = set_op_emit_count(&op, all, left_count, right_count);
                    for _ in 0..emit {
                        self.pending.push_back(key.clone());
                    }
                }
            }
        }

        Ok(Box::new(SetOpIterator {
            left_iter,
            right_iter,
            left_schema,
            right_schema,
            op: self.op,
            all: self.all,
            temp_dir: self.temp_dir.clone(),
            memory_budget: self.memory_budget,
            streams: None,
            pending: std::collections::VecDeque::new(),
        }))
    }

    fn schema(&self) -> &Schema {
        &self.schema
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!(
            "{}- PhysicalSetOp: op={:?}, all={}\n",
            "  ".repeat(indent),
            self.op,
            self.all
        ));
        out.push_str(&format!("{}  left:\n", "  ".repeat(indent)));
        self.left.explain(indent + 2, out);
        out.push_str(&format!("{}  right:\n", "  ".repeat(indent)));
        self.right.explain(indent + 2, out);
    }
}

// ==========================================
// 9. Distinct Physical Operator (Sort-based, bounded-memory)
// ==========================================
/// Deduplicates by externally sorting the source on all columns, then dropping
/// rows equal to the previously emitted one. Memory is bounded by spilling sorted
/// runs; equal rows are adjacent after the merge so a single look-back suffices.
pub struct PhysicalDistinct {
    source: Box<dyn PhysicalOperator>,
    temp_dir: PathBuf,
    memory_budget: usize,
}

enum DistinctState {
    InMemory(std::vec::IntoIter<Vec<DbValue>>),
    External {
        merger: KWayMerge<()>,
        last: Option<Vec<DbValue>>,
    },
}

impl PhysicalDistinct {
    pub fn new(source: Box<dyn PhysicalOperator>, temp_dir: PathBuf, memory_budget: usize) -> Self {
        Self {
            source,
            temp_dir,
            memory_budget,
        }
    }
}

impl PhysicalOperator for PhysicalDistinct {
    fn execute(
        &self,
        tx: &Transaction,
        params: &HashMap<String, DbValue>,
    ) -> Result<Box<dyn Iterator<Item = Result<Row, String>> + Send>, String> {
        let source_iter = self.source.execute(tx, params)?;
        let source_schema = self.source.schema().clone();

        struct DistinctIterator {
            source_iter: Box<dyn Iterator<Item = Result<Row, String>> + Send>,
            source_schema: Schema,
            temp_dir: PathBuf,
            memory_budget: usize,
            state: Option<DistinctState>,
        }

        impl Iterator for DistinctIterator {
            type Item = Result<Row, String>;

            fn next(&mut self) -> Option<Self::Item> {
                if self.state.is_none() {
                    let width = self.source_schema.columns.len();
                    let directions = vec![true; width];
                    let mut buffer: Vec<(Vec<DbValue>, ())> = Vec::new();
                    let mut buffer_bytes: usize = 0;
                    let mut runs: Vec<Run<()>> = Vec::new();

                    for row_res in self.source_iter.by_ref() {
                        let row = match row_res {
                            Ok(r) => r,
                            Err(e) => return Some(Err(e)),
                        };
                        let key = row.values;
                        buffer_bytes += spill::estimate_row_size(&key, &[]);
                        buffer.push((key, ()));

                        if buffer_bytes >= self.memory_budget {
                            spill::sort_entries(&mut buffer, &directions);
                            match spill::write_run(&self.temp_dir, "distinct_run", &buffer) {
                                Ok(run) => runs.push(run),
                                Err(e) => return Some(Err(e)),
                            }
                            buffer.clear();
                            buffer_bytes = 0;
                        }
                    }

                    if runs.is_empty() {
                        spill::sort_entries(&mut buffer, &directions);
                        let mut keys: Vec<Vec<DbValue>> =
                            buffer.into_iter().map(|(k, _)| k).collect();
                        keys.dedup();
                        self.state = Some(DistinctState::InMemory(keys.into_iter()));
                    } else {
                        if !buffer.is_empty() {
                            spill::sort_entries(&mut buffer, &directions);
                            match spill::write_run(&self.temp_dir, "distinct_run", &buffer) {
                                Ok(run) => runs.push(run),
                                Err(e) => return Some(Err(e)),
                            }
                        }
                        let merger = match KWayMerge::new(
                            runs,
                            directions,
                            &self.temp_dir,
                            "distinct_run",
                        ) {
                            Ok(m) => m,
                            Err(e) => return Some(Err(e)),
                        };
                        self.state = Some(DistinctState::External { merger, last: None });
                    }
                }

                match self.state.as_mut().unwrap() {
                    DistinctState::InMemory(iter) => Ok(iter.next().map(Row::new)).transpose(),
                    DistinctState::External { merger, last } => {
                        // Skip consecutive duplicates; equal keys are adjacent post-merge.
                        loop {
                            match merger.next() {
                                Ok(Some((key, ()))) => {
                                    if last.as_ref() != Some(&key) {
                                        *last = Some(key.clone());
                                        return Some(Ok(Row::new(key)));
                                    }
                                }
                                Ok(None) => return None,
                                Err(e) => return Some(Err(e)),
                            }
                        }
                    }
                }
            }
        }

        Ok(Box::new(DistinctIterator {
            source_iter,
            source_schema,
            temp_dir: self.temp_dir.clone(),
            memory_budget: self.memory_budget,
            state: None,
        }))
    }

    fn schema(&self) -> &Schema {
        self.source.schema()
    }

    fn explain(&self, indent: usize, out: &mut String) {
        out.push_str(&format!("{}- PhysicalDistinct\n", "  ".repeat(indent)));
        self.source.explain(indent + 1, out);
    }
}
